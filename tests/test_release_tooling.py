def test_collect_changes_since_last_tag(repo):
    changes = rt.collect_changes(repo)

    assert changes.since_tag == "v0.3.0"
    subjects = [c.subject for c in changes.commits]
    assert subjects == ["docs: log", "fix: dashboard crash", "feat(db): migrations v2 and v3"]
    assert (changes.schema_from, changes.schema_to) == (1, 3)
    # config.py only had its version bumped → not a change of the "Interfaz" area
    assert set(changes.files_by_area) == {"db", "gui", "docs"}
    assert changes.files_by_area["gui"] == ["app/gui/view.py"]
    assert changes.log_entries == ["2099-01-01 — New work"]


def test_draft_contains_every_fact_and_is_not_publishable(repo):
    changes = rt.collect_changes(repo)
    draft = rt.draft_notes(changes, "0.4.0")

    for commit in changes.commits:
        assert commit.sha in draft
    assert rt.migration_sentence(1, 3) in draft
    for label in ("Base de datos y migraciones", "Interfaz", "Documentación"):
        assert label in draft
    assert rt.verify_notes(draft, changes)   # TODOs and comments left → refused


def test_verify_notes_accepts_complete_notes_and_names_what_is_missing(repo):
    changes = rt.collect_changes(repo)
    good = rt.draft_notes(changes, "0.4.0")
    good = re.sub(r"<!--.*?-->\n?", "", good, flags=re.DOTALL)
    good = good.replace(
        "TODO: 2-4 frases sobre qué cambia al actualizar a 0.4.0.",
        "La base de datos se repara sola y el panel principal ya no se cierra con error.",
    )
    good = re.sub(r"- TODO: (.*) \(`(\w+)`\)", r"- \1 (`\2`)", good)
    assert rt.verify_notes(good, changes) == []

    missing = good.replace(changes.commits[0].sha, "xxxxxxx").replace("**Interfaz**", "**UI**")
    missing = missing.replace(rt.migration_sentence(1, 3), "Se migra la base.")
    problems = "\n".join(rt.verify_notes(missing, changes))
    assert changes.commits[0].sha in problems
    assert "Interfaz" in problems
    assert "v1 a v3" in problems


