def test_build_script_writes_marker_only_after_success(tmp_path, monkeypatch):
    import tools.build_windows as bw

    monkeypatch.setattr(bw, "ROOT", tmp_path)
    (tmp_path / "app").mkdir()
    (tmp_path / "app" / "config.py").write_text('APP_VERSION = "0.4.0"\n', encoding="utf-8")
    marker = tmp_path / "dist" / "PROFIN.R.0.4.0.build-ok"

    def crashed(*args, **kwargs):
        raise subprocess.CalledProcessError(1, "pyinstaller")

    monkeypatch.setattr(sys, "argv", ["build_windows.py", "--channel", "release"])
    monkeypatch.setattr(bw.subprocess, "run", crashed)
    (tmp_path / "dist").mkdir()
    marker.write_text("stale", encoding="utf-8")
    with pytest.raises(subprocess.CalledProcessError):
        bw.main()
    assert not marker.exists()          # stale marker removed, never rewritten

    def succeeded(*args, **kwargs):
        exe = tmp_path / "dist" / "PROFIN.R.0.4.0" / "PROFIN.R.0.4.0.exe"
        exe.parent.mkdir(parents=True, exist_ok=True)
        exe.write_bytes(b"MZ")

    monkeypatch.setattr(bw.subprocess, "run", succeeded)
    assert bw.main() == 0
    assert marker.is_file()
