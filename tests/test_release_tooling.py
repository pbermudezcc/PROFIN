def _released_repo(repo: Path, notes: str) -> None:
    """Simulate steps 4-6 of the skill on the throwaway repo."""
    summary, body = rt.split_notes(notes)
    (repo / "app" / "config.py").write_text(
        f'APP_VERSION = "0.4.0"\nAPP_RELEASE_DATE = "{date.today().isoformat()}"\n', encoding="utf-8")
    (repo / "versions").mkdir()
    for suffix in (".md", ".prj"):
        (repo / "versions" / f"FAMILYFIN.R.0.4.0{suffix}").write_text("x", encoding="utf-8")
    (repo / "CHANGELOG.md").write_text(
        "# FAMILYFIN — Changelog\n\n---\n\n**Snapshot:** `FAMILYFIN.R.0.4.0.md`\n"
        f"**Description:** {summary}\n\n{body}\n", encoding="utf-8")
    _git(repo, "add", ".")
    _git(repo, "commit", "-qm", "chore(release): v0.4.0")
    notes_file = repo.parent / "notes.md"
    notes_file.write_text(notes, encoding="utf-8")
    _git(repo, "tag", "-a", "v0.4.0", "--cleanup=verbatim", "-F", str(notes_file))
    zip_path = rt.build_zip("0.4.0", "R", repo)
    zip_path.parent.mkdir(parents=True)
    zip_path.write_bytes(b"PK")


def test_postflight_checks_changelog_tag_package_and_github_release(repo):
    _released_repo(repo, NOTES)
    assert rt.postflight("0.4.0", "R", NOTES, root=repo) == []

    release = {
        "tagName": "v0.4.0", "body": NOTES, "isDraft": False, "isPrerelease": False,
        "assets": [{"name": "PROFIN.R.0.4.0-windows.zip"}],
    }
    import json
    ok_runner = lambda args: json.dumps(release)
    assert rt.postflight("0.4.0", "R", NOTES, root=repo, published=True, runner=ok_runner) == []

    bad = {**release, "body": "Otra cosa", "assets": [{"name": "PROFIN.R.0.4.0.exe"}]}
    problems = rt.postflight("0.4.0", "R", NOTES, root=repo, published=True,
                             runner=lambda args: json.dumps(bad))
    assert any("texto de la release" in p for p in problems)
    assert any("windows.zip" in p for p in problems)


def test_postflight_detects_tag_message_stripped_of_headings(repo):
    _released_repo(repo, NOTES)
    _git(repo, "tag", "-d", "v0.4.0")
    notes_file = repo.parent / "notes.md"
    _git(repo, "tag", "-a", "v0.4.0", "-F", str(notes_file))   # default cleanup=strip
    problems = rt.postflight("0.4.0", "R", NOTES, root=repo)
    assert any("mensaje del tag" in p for p in problems)


def test_postflight_detects_changelog_without_notes(repo):
    _released_repo(repo, NOTES)
    (repo / "CHANGELOG.md").write_text(
        "# FAMILYFIN — Changelog\n\n---\n\n**Snapshot:** `FAMILYFIN.R.0.4.0.md`\n"
        "**Description:** (no description)\n", encoding="utf-8")
    problems = rt.postflight("0.4.0", "R", NOTES, root=repo)
    assert any("resumen" in p for p in problems)
    assert any("cuerpo" in p for p in problems)


