@pytest.fixture
def evh_root(tmp_path, monkeypatch):
    (tmp_path / "app").mkdir()
    (tmp_path / "app" / "config.py").write_text(
        'APP_NAME    = "FAMILYFIN"\nAPP_VERSION = "0.3.0"\nAPP_RELEASE_DATE = "2026-09-16"\n',
        encoding="utf-8",
    )
    (tmp_path / "main.py").write_text("print('hola')\n", encoding="utf-8")
    (tmp_path / "CHANGELOG.md").write_text(CHANGELOG_SEED, encoding="utf-8")
    monkeypatch.setattr(evh, "ROOT", tmp_path)
    monkeypatch.setattr(evh, "VERSIONS_DIR", tmp_path / "versions")
    monkeypatch.setattr("builtins.input", lambda *a: pytest.fail("export_version prompted"))
    return tmp_path


def test_export_version_is_non_interactive_and_writes_full_notes(evh_root):
    summary, body = rt.split_notes(NOTES)
    evh.export_version(version="0.4.0", ver_type="R", also_prj=True,
                       description=summary, notes=body)

    config = (evh_root / "app" / "config.py").read_text(encoding="utf-8")
    assert 'APP_VERSION = "0.4.0"' in config
    assert f'APP_RELEASE_DATE = "{date.today().isoformat()}"' in config
    assert (evh_root / "versions" / "FAMILYFIN.R.0.4.0.md").is_file()
    assert (evh_root / "versions" / "FAMILYFIN.R.0.4.0.prj").is_file()

    changelog = (evh_root / "CHANGELOG.md").read_text(encoding="utf-8")
    entries = changelog.split("\n---\n")
    assert entries[0].startswith("# FAMILYFIN — Changelog")
    assert "`FAMILYFIN.R.0.4.0.md`" in entries[1]
    assert f"**Description:** {summary}" in entries[1]
    assert "- Copias de seguridad automáticas." in entries[1]
    assert "`FAMILYFIN.R.0.3.0.md`" in entries[2]   # older entry kept, below


